#!/usr/bin/env node

/**
 * Builds the deployable, reviewed subset for the AI basic-plan generator from
 * the client exercise library. The full 873-item reference catalogue is never
 * used as an automatic generator allowlist.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { BASIC_WORKOUT_EXERCISE_LIBRARY } from "../src/data/basicWorkoutExerciseLibrary.js";

const DISABLED_AI_IDS = new Set([
  "deadlift",
  "barbell_row",
  "machine_row",
  "barbell_bench_press",
  "incline_machine_press",
  "low_incline_pushup",
  "standing_db_press"
]);

const ROLE_BY_GROUP = {
  quads: "kneeDominantCompound",
  posterior_chain: "hipDominantCompound",
  calves: "lowerAccessory",
  vertical_pull: "verticalPull",
  horizontal_pull: "horizontalPull",
  chest_press: "chestPress",
  chest_incline: "chestPress",
  chest_fly: "chestAccessory",
  shoulder_press: "shoulderPress",
  side_delts: "shoulderAccessory",
  rear_delts: "shoulderAccessory",
  biceps: "biceps",
  triceps: "triceps",
  core: "core"
};

const ROLE_BY_ID = {
  leg_extension: "lowerAccessory",
  leg_curl: "lowerAccessory",
  back_extension: "lowerAccessory",
  standing_calf_raise: "lowerAccessory",
  seated_calf_raise: "lowerAccessory",
  leg_press_calf_raise: "lowerAccessory",
  single_leg_calf_raise: "lowerAccessory"
};

function toSeconds(value = "") {
  const parsed = Number.parseInt(String(value), 10);
  return Number.isFinite(parsed) ? Math.min(180, Math.max(30, parsed)) : 75;
}

export function buildBasicWorkoutAiCatalogue(library = BASIC_WORKOUT_EXERCISE_LIBRARY) {
  const seenIds = new Set();
  const catalogue = library
    .filter((exercise) => !DISABLED_AI_IDS.has(exercise.id))
    .map((exercise) => {
      if (seenIds.has(exercise.id)) throw new Error(`Duplicate basic workout AI catalogue id: ${exercise.id}`);
      seenIds.add(exercise.id);
      const movementRole = ROLE_BY_ID[exercise.id] || ROLE_BY_GROUP[exercise.groupId];
      if (!movementRole) throw new Error(`Missing movement role for ${exercise.id}`);

      return {
        id: exercise.id,
        name: exercise.name,
        aliases: Array.isArray(exercise.aliases) ? exercise.aliases : [],
        groupId: exercise.groupId,
        movementRole,
        equipment: exercise.equipment,
        locations: Array.isArray(exercise.locations) ? exercise.locations : [],
        requiresWeight: Boolean(exercise.requiresWeight),
        restSeconds: toSeconds(exercise.rest),
        durationSeconds: Number(exercise.durationSeconds) || 0,
        note: exercise.note
      };
    })
    .sort((left, right) => left.id.localeCompare(right.id, "en"));

  if (catalogue.length < 50) throw new Error("The AI catalogue unexpectedly contains fewer than 50 reviewed exercises.");
  return catalogue;
}

export async function writeBasicWorkoutAiCatalogue(outputPath, catalogue = buildBasicWorkoutAiCatalogue()) {
  const destination = path.resolve(outputPath);
  const source = [
    "// Generated by scripts/build-basic-workout-ai-catalogue.mjs. Do not edit by hand.",
    `export const BASIC_WORKOUT_AI_CATALOGUE = ${JSON.stringify(catalogue, null, 2)};`,
    ""
  ].join("\n");
  await fs.writeFile(destination, source, "utf8");
}

async function runCli() {
  const output = process.argv[2] || "functions/basicWorkoutAiCatalogue.generated.js";
  await writeBasicWorkoutAiCatalogue(output);
  console.log(JSON.stringify({ exerciseCount: buildBasicWorkoutAiCatalogue().length, output }, null, 2));
}

const executedAsScript = process.argv[1]
  && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (executedAsScript) {
  runCli().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
