function normalizeQuery(value) {
  return String(value || "")
    .normalize("NFKC")
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s.-]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function addTerms(target, terms) {
  terms.forEach((term) => {
    const normalized = String(term || "").trim().toLocaleLowerCase("en");
    if (normalized) target.add(normalized);
  });
}

export function expandRussianNutritionQuery(query) {
  const normalized = normalizeQuery(query);
  if (!/[а-я]/u.test(normalized)) return [];

  const expansions = new Set();
  const paddedQuery = ` ${normalized} `;

  Object.entries(PHRASE_EXPANSIONS).forEach(([phrase, terms]) => {
    if (paddedQuery.includes(` ${phrase} `)) addTerms(expansions, terms);
  });

  normalized.split(/[\s.-]+/u).filter(Boolean).forEach((token) => {
    addTerms(expansions, TOKEN_EXPANSIONS[token] || []);
    STEM_EXPANSIONS.forEach(([stem, terms]) => {
      if (token.startsWith(stem)) addTerms(expansions, terms);
    });
  });

  return [...expansions];
}

